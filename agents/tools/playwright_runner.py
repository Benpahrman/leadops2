async def apply_stealth_evasions(context: BrowserContext) -> None:
    """Mask browser automation flags and normalize navigator fingerprints."""
    await context.add_init_script("""
        // Hide Playwright / Chrome automated webdriver flag
        Object.defineProperty(navigator, 'webdriver', {{ get: () => undefined }});
        
        // Emulate realistic plugins and languages
        Object.defineProperty(navigator, 'languages', {{ get: () => ['en-US', 'en'] }});
        Object.defineProperty(navigator, 'plugins', {{ get: () => [1, 2, 3, 4, 5] }});
        
        // Emulate realistic hardware concurrency & device memory
        Object.defineProperty(navigator, 'hardwareConcurrency', {{ get: () => 8 }});
        Object.defineProperty(navigator, 'deviceMemory', {{ get: () => 8 }});

        // Pass WebGL vendor & renderer checks
        const getParameter = WebGLRenderingContext.prototype.getParameter;
        WebGLRenderingContext.prototype.getParameter = function(parameter) {{
            if (parameter === 37445) return 'Google Inc. (Intel)';
            if (parameter === 37446) return 'ANGLE (Intel, Intel(R) UHD Graphics 630 Direct3D11 vs_5_0 ps_5_0, D3D11)';
            return getParameter.apply(this, arguments);
        }};

        // Emulate chrome runtime object
        window.chrome = {{
            runtime: {{}},
            app: {{ isInstalled: false }},
        }};
    """)


async def handle_captchas_and_challenges(page: Page) -> bool:
    """Detect and handle Cloudflare Turnstile, reCAPTCHA, and hCaptcha bot challenges."""
    try:
        # 1. Cloudflare Turnstile / Managed Challenge detection
        cf_frames = await page.query_selector_all("iframe[src*='challenges.cloudflare.com'], iframe[src*='turnstile'], div.cf-turnstile")
        if cf_frames:
            logger.info("🛡️ [ANTI-BOT] Cloudflare challenge / Turnstile detected. Emulating human interaction...")
            for frame_el in cf_frames:
                try:
                    if await frame_el.is_visible():
                        box = await frame_el.bounding_box()
                        if box:
                            # Human-like bezier mouse trajectory
                            await page.mouse.move(box["x"] + box["width"] / 2, box["y"] + box["height"] / 2, steps=12)
                            await asyncio.sleep(random.uniform(0.3, 0.7))
                            await page.mouse.click(box["x"] + box["width"] / 2, box["y"] + box["height"] / 2)
                            logger.info("Clicked Cloudflare Turnstile checkbox. Awaiting verification token...")
                            await page.wait_for_timeout(4000)
                            return True
                except Exception as e:
                    logger.debug("Turnstile frame interaction note: %s", e)

        # 2. reCAPTCHA v2/v3 detection
        recaptcha_frames = await page.query_selector_all("iframe[src*='recaptcha'], div.g-recaptcha")
        if recaptcha_frames:
            logger.info("🛡️ [ANTI-BOT] reCAPTCHA challenge detected.")
            # Check for existing response token or 2Captcha solver hook
            captcha_key = os.getenv("CAPTCHA_SOLVER_KEY")
            if captcha_key:
                logger.info("Dispatching sitekey to automated CAPTCHA solver token hook...")
                # Solver integration hook can inject g-recaptcha-response token here
                return True

        # 3. Check for standard 'I am not a robot' or verification checkboxes
        verify_checkboxes = await page.query_selector_all("input[type='checkbox'][name*='robot' i], input[id*='challenge' i]")
        for chk in verify_checkboxes:
            if await chk.is_visible():
                await chk.click()
                await page.wait_for_timeout(2000)
                return True

    except Exception as exc:
        logger.warning("Captcha handling inspection note: %s", exc)
    return False


async def handle_search_forms(page: Page) -> bool:
    """Detect and automatically submit registry search forms with recent date ranges."""
    try:
        from_inputs = await page.query_selector_all("input[name*='From' i], input[id*='From' i], input[name*='start' i]")
        to_inputs = await page.query_selector_all("input[name*='To' i], input[id*='To' i], input[name*='end' i]")

        if from_inputs and to_inputs:
            today = datetime.now()
            from_date = (today - timedelta(days=30)).strftime("%m/%d/%Y")
            to_date = today.strftime("%m/%d/%Y")
            logger.info("Filling search date range: %s to %s...", from_date, to_date)

            for inp in from_inputs:
                try:
                    if await inp.is_visible():
                        await inp.fill(from_date)
                        break
                except Exception as e:
                    await page.evaluate("(el, val) => {{ el.value = val; el.dispatchEvent(new Event('input', {{bubbles: true}})); }}", inp, from_date)
                    break

            for inp in to_inputs:
                try:
                    if await inp.is_visible():
                        await inp.fill(to_date)
                        break
                except Exception as e:
                    await page.evaluate("(el, val) => {{ el.value = val; el.dispatchEvent(new Event('input', {{bubbles: true}})); }}", inp, to_date)
                    break

            buttons = await page.query_selector_all("input[type='submit'], input[name*='Search' i], button[type='submit'], button:has-text('Search'), a:has-text('Search')")
            for btn in buttons:
                try:
                    if await btn.is_visible():
                        logger.info("Submitting search query via visible search button...")
                        await btn.click()
                        try:
                            await page.wait_for_load_state("networkidle", timeout=15000)
                        except Exception:
                            await asyncio.sleep(4)
                        return True
                except Exception:
                    continue
    except Exception as e:
        logger.warning("Search form interaction note: %s", e)
    return False


async def extract_page_records(page: Page, primary_selector: str, field_mapping: dict[str, str]) -> list[dict[str, str]]:
    """Extract structured tabular records using a robust multi-strategy selector cascade."""
    rows = []
    
    header_map = {{}}
    th_elements = await page.query_selector_all("table tr th, table tr td.header, thead tr td")
    for idx, th in enumerate(th_elements):
        th_text = (await th.inner_text()).strip().lower()
        if any(k in th_text for k in ["case", "file #", "number", "id", "cause"]):
            header_map["case_number"] = idx
        elif any(k in th_text for k in ["date", "file date", "filing"]):
            header_map["filing_date"] = idx
        elif any(k in th_text for k in ["style", "decedent", "estate", "name", "title", "party"]):
            header_map["title"] = idx
        elif any(k in th_text for k in ["status", "state"]):
            header_map["status"] = idx

    candidate_selectors = [
        "table tr:not(:first-child)",
        "table tbody tr",
        "table.table tr",
        "table.grid tr",
        "[role='row']",
        "div[class*='row']",
        "div[class*='record']",
        "div[class*='item']",
    ]

    matched_elements = []
    for sel in candidate_selectors:
        try:
            els = await page.query_selector_all(sel)
            if len(els) >= 1:
                data_rows = []
                for test_el in els:
                    try:
                        tds = await test_el.query_selector_all("td")
                        if len(tds) >= 2:
                            data_rows.append(test_el)
                    except Exception:
                        continue
                if data_rows:
                    matched_elements = data_rows
                    break
        except Exception:
            continue

    if not matched_elements:
        for sel in candidate_selectors:
            try:
                els = await page.query_selector_all(sel)
                if len(els) >= 1:
                    matched_elements = els
                    break
            except Exception:
                continue

    for row_el in matched_elements[:MAX_ROWS]:
        row_data = {{}}
        td_elements = await row_el.query_selector_all("td")
        cell_texts = [(await td.inner_text()).strip() for td in td_elements]
        
        if any("file date" in c.lower() or "case" in c.lower() for c in cell_texts[:3]):
            continue

        for idx, (field_name, sel) in enumerate(field_mapping.items()):
            val = ""
            if field_name in header_map and header_map[field_name] < len(cell_texts):
                val = cell_texts[header_map[field_name]]
            if not val and sel and sel != ".":
                try:
                    el = await row_el.query_selector(sel)
                    if el:
                        val = (await el.inner_text()).strip()
                except Exception:
                    pass
            if not val and idx < len(cell_texts):
                val = cell_texts[idx]
            row_data[field_name] = val

        if any(row_data.values()) and any(len(str(v)) > 1 for v in row_data.values()):
            # Pydantic validation
            schema_instance = RecordSchema(
                record_id=row_data.get("record_id") or row_data.get("case_number"),
                filing_date=row_data.get("filing_date"),
                case_number=row_data.get("case_number"),
                title=row_data.get("title") or row_data.get("decedent_name") or row_data.get("company_name"),
                status=row_data.get("status", "ACTIVE"),
                raw_payload=row_data,
            )
            rows.append(row_data)

    return rows


async def run_pipeline() -> list[dict[str, Any]]:
    """Main extraction pipeline with exponential backoff retries, stealth headers, and proxy support."""
    results: list[dict[str, Any]] = []

    for attempt in range(1, MAX_RETRIES + 1):
        try:
            logger.info("Starting extraction attempt %d/%d on %s...", attempt, MAX_RETRIES, TARGET_URL)

            async with async_playwright() as p:
                launch_options = {{
                    "headless": True,
                    "args": [
                        "--disable-blink-features=AutomationControlled",
                        "--no-sandbox",
                        "--disable-dev-shm-usage",
                        "--disable-gpu",
                    ]
                }}

                if PROXY_URL:
                    launch_options["proxy"] = {{"server": PROXY_URL}}
                    logger.info("Routing through rotating proxy pool...")

                browser = await p.chromium.launch(**launch_options)
                context = await browser.new_context(
                    viewport={{"width": 1920, "height": 1080}},
                    user_agent="Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36",
                    locale="en-US",
                    timezone_id="America/Chicago",
                )

                await apply_stealth_evasions(context)
                page = await context.new_page()

                await page.set_extra_http_headers({{
                    "Accept-Language": "en-US,en;q=0.9",
                    "Sec-Ch-Ua": '"Chromium";v="124", "Google Chrome";v="124", "Not-A.Brand";v="99"',
                    "Sec-Ch-Ua-Mobile": "?0",
                    "Sec-Ch-Ua-Platform": '"Windows"',
                }})

                await page.goto(TARGET_URL, timeout=TIMEOUT_MS, wait_until="domcontentloaded")
                await asyncio.sleep(random.uniform(1.2, 2.5))

                # Handle bot challenges & search forms
                await handle_captchas_and_challenges(page)
                await handle_search_forms(page)

                if "{task_wait_selector}":
                    try:
                        await page.wait_for_selector("{task_wait_selector}", timeout=TIMEOUT_MS)
                    except Exception as e:
                        logger.warning("Wait selector timed out: %s", e)

                extracted = await extract_page_records(page, PRIMARY_ROW_SELECTOR, FIELD_SELECTORS)
                results.extend(extracted[:MAX_ROWS])

                await browser.close()
                logger.info("Successfully extracted %d records!", len(results))
                return results

        except Exception as err:
            backoff_delay = (2 ** attempt) + random.uniform(0.5, 1.5)
            logger.warning("Attempt %d failed (%s: %s). Retrying in %.2fs...", attempt, type(err).__name__, err, backoff_delay)
            await asyncio.sleep(backoff_delay)

    raise RuntimeError("Extraction failed after " + str(MAX_RETRIES) + " attempts.")


def deliver_records(records: list[dict[str, Any]]) -> dict[str, Any]:
    """Standalone delivery dispatcher: Local JSON/CSV, Google Sheets, and CRM Webhooks."""
    if not records:
        logger.warning("No records extracted to deliver.")
        return {{"saved_local": 0, "google_sheets_appended": 0, "webhook_delivered": False}}

    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    os.makedirs("output", exist_ok=True)
    os.makedirs("runs", exist_ok=True)

    # 1. Local JSON Exporters
    json_path = os.path.join("output", "latest.json")
    run_json_path = os.path.join("runs", "run_%s.json" % timestamp)
    with open(json_path, "w", encoding="utf-8") as f:
        json.dump(records, f, indent=2)
    with open(run_json_path, "w", encoding="utf-8") as f:
        json.dump(records, f, indent=2)
    logger.info("💾 [SAVED] %d records saved to %s & %s", len(records), json_path, run_json_path)

    # 2. Local CSV Exporter
    csv_path = os.path.join("output", "latest.csv")
    with open(csv_path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=list(records[0].keys()))
        writer.writeheader()
        writer.writerows(records)
    logger.info("💾 [SAVED] %d records saved to %s", len(records), csv_path)

    # 3. Google Sheets Delivery (Every morning by 8:00 AM)
    sheets_appended = 0
    if GOOGLE_SHEETS_ID:
        try:
            import gspread
            gc = gspread.service_account()
            sh = gc.open_by_key(GOOGLE_SHEETS_ID)
            worksheet = sh.get_worksheet(0) or sh.sheet1
            existing = worksheet.get_all_values()
            if not existing:
                worksheet.append_row(list(records[0].keys()))
            worksheet.append_rows([list(r.values()) for r in records])
            sheets_appended = len(records)
            logger.info("📊 [GOOGLE SHEETS DELIVERED] Appended %d rows to sheet %s", sheets_appended, GOOGLE_SHEETS_ID)
        except Exception as e:
            logger.warning("Google Sheets sync notice (gspread): %s", e)

    # 4. CRM Webhook Delivery (HubSpot / Salesforce / Custom)
    webhook_delivered = False
    if CRM_WEBHOOK_URL:
        try:
            import urllib.request
            payload = json.dumps({{
                "delivered_at": datetime.now(timezone.utc).isoformat(),
                "scheduled_sla": "08:00 AM Daily",
                "count": len(records),
                "records": records,
            }}).encode("utf-8")
            req = urllib.request.Request(
                CRM_WEBHOOK_URL,
                data=payload,
                headers={{"Content-Type": "application/json", "User-Agent": "LeadOps-8AM-Delivery/2.0"}}
            )
            with urllib.request.urlopen(req, timeout=20) as resp:
                if 200 <= resp.status < 300:
                    webhook_delivered = True
                    logger.info("🚀 [CRM WEBHOOK DELIVERED] Dispatched %d records to %s", len(records), CRM_WEBHOOK_URL)
        except Exception as e:
            logger.warning("CRM Webhook delivery note: %s", e)

    return {{
        "saved_local": len(records),
        "json_path": json_path,
        "csv_path": csv_path,
        "google_sheets_appended": sheets_appended,
        "webhook_delivered": webhook_delivered,
    }}


