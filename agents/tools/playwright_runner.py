    while True:
        now = datetime.now()
        target = now.replace(hour=8, minute=0, second=0, microsecond=0)
        if now >= target:
            target += timedelta(days=1)
        sleep_seconds = (target - now).total_seconds()
        logger.info("Next 8:00 AM delivery scheduled in %.1f hours (%s)", sleep_seconds / 3600, target.strftime("%Y-%m-%d %H:%M:%S"))
        time.sleep(sleep_seconds)

