class PlaywrightRunner:
    """Safely executes web extractions using Playwright with graceful fallbacks."""

    def __init__(self, headless: bool = True) -> None:
        self.headless = headless

    async def execute_task_async(self, task: ScraperTask) -> list[dict[str, str]]:
        """Run extraction in Playwright async session with full error handling."""
        try:
            from playwright.async_api import async_playwright
            async with async_playwright() as p:
                launch_options: dict[str, Any] = {
                    "headless": self.headless,
                    "args": ["--disable-blink-features=AutomationControlled", "--no-sandbox"],
                }
                if task.proxy_url:
                    launch_options["proxy"] = {"server": task.proxy_url}

                browser = await p.chromium.launch(**launch_options)
                context = await browser.new_context(
                    user_agent="Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36"
                )
                page = await context.new_page()
                await page.goto(task.url, timeout=task.timeout_ms, wait_until="domcontentloaded")

                if task.wait_selector:
                    try:
                        await page.wait_for_selector(task.wait_selector, timeout=task.timeout_ms)
                    except Exception as e:
                        logger.debug("Wait selector '%s' timed out: %s", task.wait_selector, e)

                rows_elements = await page.query_selector_all(task.row_selector)
                extracted_rows: list[dict[str, str]] = []
                for row_el in rows_elements[:task.max_rows]:
                    row_data: dict[str, str] = {}
                    for field_name, selector in task.field_selectors.items():
                        try:
                            field_el = await row_el.query_selector(selector) if selector != "." else row_el
                            if field_el:
                                text = await field_el.inner_text()
                                row_data[field_name] = text.strip()
                            else:
                                row_data[field_name] = ""
                        except Exception as e:
                            logger.debug("Field extraction failed for %s: %s", field_name, e)
                            row_data[field_name] = ""
                    if any(row_data.values()):
                        extracted_rows.append(row_data)

                await browser.close()
                return extracted_rows
        except (RuntimeError, ConnectionError) as e:
            raise RuntimeError(f"Playwright extraction failed: {e}") from e
        except Exception as e:
            logger.error("Unexpected Playwright error: %s: %s", type(e).__name__, e)
            raise RuntimeError(f"Playwright extraction failed: {e}") from e

    def execute_task(self, task: ScraperTask) -> list[dict[str, str]]:
        """Synchronous wrapper for executing scraper task."""
        try:
            loop = asyncio.get_running_loop()
        except RuntimeError:
            loop = None

        if loop and loop.is_running():
            try:
                import nest_asyncio
                nest_asyncio.apply()
                return asyncio.run(self.execute_task_async(task))
            except ImportError:
                with concurrent.futures.ThreadPoolExecutor(max_workers=1) as pool:
                    return pool.submit(asyncio.run, self.execute_task_async(task)).result()
        else:
            return asyncio.run(self.execute_task_async(task))